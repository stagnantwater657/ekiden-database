import { readFileSync, writeFileSync, renameSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { assembleDatabase } from "../lib/data-assembly.ts";
import { validateDatabase } from "../lib/repository.ts";
import {
  mergeRegistry,
  validateImport,
  importReport,
} from "../lib/importer.ts";
import type { Registry, EditionBundle } from "../lib/model.ts";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (path: string) =>
  JSON.parse(readFileSync(resolve(root, path), "utf8"));
const atomic = (path: string, value: string) => {
  const full = resolve(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full + ".tmp", value);
  renameSync(full + ".tmp", full);
};
let registry = read("data/registry/entities.json") as Registry;
const manifest = read("data/manifest.json") as string[];
if (
  !Array.isArray(manifest) ||
  manifest.some((id) => !/^[-a-z0-9]+$/.test(id)) ||
  new Set(manifest).size !== manifest.length
)
  throw new Error("Invalid edition manifest");
const batches = manifest.map(
  (id) => read(`data/editions/${id}.json`) as EditionBundle,
);
const args = process.argv.slice(2);
if (args[0] === "--export") {
  if (args.length !== 2) throw new Error("Usage: --export edition-id");
  const batch = batches.find((b) => b.edition.id === args[1]);
  if (!batch) throw new Error("Unknown edition");
  process.stdout.write(JSON.stringify({ registry, batch }, null, 2) + "\n");
  process.exit(0);
}
if (
  args.length &&
  !(
    args[0] === "--input" &&
    (args.length === 2 || (args.length === 3 && args[2] === "--write"))
  )
)
  throw new Error("Usage: data-import.ts [--input candidate.json [--write]]");
let database = assembleDatabase(registry, batches);
if (args[0] === "--input") {
  const input = read(args[1]) as { registry: Registry; batch: EditionBundle };
  if (!/^[-a-z0-9]+$/.test(input.batch.edition.id))
    throw new Error("Invalid edition ID");
  registry = mergeRegistry(registry, input.registry);
  database = validateImport(registry, batches, input.batch);
  if (!batches.some((batch) => batch.edition.id === input.batch.edition.id)) batches.push(input.batch);
  if (args.includes("--write")) {
    const id = input.batch.edition.id;
    if (!manifest.includes(id)) manifest.push(id);
    manifest.sort();
    // Validate everything before any publication; manifest is committed last.
    atomic(
      `data/editions/${id}.json`,
      JSON.stringify(input.batch, null, 2) + "\n",
    );
    atomic(
      "data/registry/entities.json",
      JSON.stringify(registry, null, 2) + "\n",
    );
    const imports = manifest
      .map(
        (id, i) =>
          `import batch${i} from './editions/${id}.json' with {type:'json'};`,
      )
      .join("\n");
    atomic(
      "data/index.ts",
      `// Generated by npm run data:import; do not hand edit.\nimport entities from './registry/entities.json' with {type:'json'};\n${imports}\nimport { assembleDatabase } from '../lib/data-assembly.ts';\nimport type { Registry, EditionBundle } from '../lib/model.ts';\nexport const registry = entities as Registry;\nexport const batches = [${manifest.map((_, i) => `batch${i} as EditionBundle`).join(",")}];\nexport const database = assembleDatabase(registry, batches);\n`,
    );
    atomic("data/manifest.json", JSON.stringify(manifest, null, 2) + "\n");
  }
}
validateDatabase(database);
for (const batch of batches) validateImport(registry, batches, batch);
const reports = database.editions.map((e) => importReport(database, e.id));
process.stdout.write(
  JSON.stringify({ schemaVersion: 2, reports }, null, 2) + "\n",
);
